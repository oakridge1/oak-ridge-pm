export function ProposalTab() {
  const { state, setState, calcBid } = useEstimatorContext();
  const p = state.proposal;

  const patch = useCallback(<K extends keyof ProposalState>(
    key: K, value: ProposalState[K],
  ) => {
    setState(s => ({ ...s, proposal: { ...s.proposal, [key]: value } }));
  }, [setState]);

  const bid = useMemo(() => calcBid(), [calcBid]);

  // ── Correct grand total (mirrors BidSummaryTab — includes height adder,
  //    actual permit/sub/rental dollar amounts, and lighting/gear quoted costs)
  const R                   = getRates();
  const effectiveLaborTotal = bid.laborTotal * (state.heightAdder ? 1.10 : 1.0);
  const effectiveOverhead   = effectiveLaborTotal * R.overhead;
  const permitEntries       = state.permits.filter(ent => !ent.desc.startsWith('[Rental]'));
  const rentalEntries       = state.permits.filter(ent =>  ent.desc.startsWith('[Rental]'));
  const permitTotal         = permitEntries.reduce((s, ent) => s + ent.cost, 0) * (1 + R.permit);
  const rentalTotal         = rentalEntries.reduce((s, ent) => s + ent.cost, 0) * (1 + R.bulk);
  const subTotal            = state.subs.reduce((s, ent) => s + ent.cost, 0)   * (1 + R.sub);
  const lightingPerUnit     = state.lightingSchedule.reduce((sum, item) => {
    if (!item.quotedPrice || !item.qty) return sum;
    return sum + item.quotedPrice * item.qty * (1 + item.markup);
  }, 0);
  const lightingCost        = state.lightingTotalQuote
    ? state.lightingTotalQuote * (1 + (state.lightingQuoteMarkup ?? 0.05))
    : lightingPerUnit;
  const gearPerUnit         = state.gearSchedule.reduce((sum, item) => {
    if (!item.quotedPrice || !item.qty) return sum;
    return sum + item.quotedPrice * item.qty * (1 + item.markup);
  }, 0);
  const gearCost            = state.gearTotalQuote
    ? state.gearTotalQuote * (1 + (state.gearQuoteMarkup ?? 0.05))
    : gearPerUnit;
  const correctSubtotal     = bid.matTotal + effectiveLaborTotal + effectiveOverhead
                            + permitTotal + rentalTotal + subTotal
                            + lightingCost + gearCost;
  const correctGrandTotal   = correctSubtotal * (1 + R.profit);

  // ── Per-label proportional totals (for alternates and Base Bid row) ─────────
  const labelTotals  = useMemo(() => calcLabelTotals(state), [state]);
  // If assemblies are labeled, Base Bid row = labeled Base Bid share; else full total
  const baseBidTotal = Math.round((labelTotals['Base Bid']?.total ?? correctGrandTotal) * 100) / 100;

  // ── Base Bid manual override (for T&M / legacy unlabeled adjustments) ───────
  const [baseBidOverride, setBaseBidOverride] = useState<number | null>(null);
  const displayBaseBid = baseBidOverride ?? baseBidTotal;

  // ── Smart scope detection ───────────────────────────────────────
  const hasFAWork   = state.savedFA.length   > 0;
  const hasDataWork = state.savedData.length > 0;
  const hasLVWork   = state.savedLV.length   > 0;

  const hasFASection = p.scopeSections.some(s =>
    s.title.toLowerCase().includes('fire alarm') ||
    s.title.toLowerCase().includes(' fa'));
  const hasDataSection = p.scopeSections.some(s =>
    s.title.toLowerCase().includes('data') ||
    s.title.toLowerCase().includes('low voltage') ||
    s.title.toLowerCase().includes(' lv'));

  // ── Auto-sync GC info → proposal client fields (when clientCompany is empty) ──
  useEffect(() => {
    if (!state.proposal.clientCompany && state.jobInfo.gcCompany) {
      setState(s => ({
        ...s,
        proposal: {
          ...s.proposal,
          clientCompany: s.jobInfo.gcCompany,
          clientAttn:    s.jobInfo.gcContactName || '',
        },
      }));
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [state.jobInfo.gcCompany, state.jobInfo.gcContactName]);

  // ── Auto-sync estimator bid packages → proposal alternates ──────────────────
  // Any bid package in the label system that is NOT "Base Bid" gets an alternate
  // row auto-populated with a proportional share of the project grand total.
  // Title/desc edits are preserved; price stays live.
  useEffect(() => {
    const totals = calcLabelTotals(state);

    // Only non-base packages that exist in the label registry
    const estimatorPkgs = (state.labelsBidPackage ?? [])
      .filter(p => p !== 'Base Bid' && p !== '(No Package)');

    setState(prev => {
      const current = prev.proposal.alternates;

      // 1. Remove alternates that were auto-synced but whose package was deleted
      let filtered = current.filter(
        a => !a.bidPackage || estimatorPkgs.includes(a.bidPackage),
      );

      // 2. When estimator packages exist, also drop blank manual alternates
      //    (no title, no desc, $0 price, no bidPackage) so they don't stack
      if (estimatorPkgs.length > 0) {
        filtered = filtered.filter(
          a => a.bidPackage || a.title || a.desc || a.price > 0,
        );
      }

      // 3. Upsert each estimator package
      const result = [...filtered];
      for (const pkg of estimatorPkgs) {
        const t     = totals[pkg] ?? { raw: 0, total: 0 };
        const price = Math.round(t.total);
        const idx   = result.findIndex(a => a.bidPackage === pkg);
        if (idx >= 0) {
          // Preserve title / desc; only refresh the price
          result[idx] = { ...result[idx], price };
        } else {
          const nextNum = result.length > 0
            ? Math.max(...result.map(a => a.number)) + 1
            : 1;
          result.push({
            id:         uid(),
            number:     nextNum,
            title:      pkg,
            desc:       '',
            price,
            bidPackage: pkg,
          });
        }
      }

      // 4. Re-number to keep a clean 1, 2, 3… sequence
      const renumbered = result.map((a, i) => ({ ...a, number: i + 1 }));

      // 5. Bail out (no re-render) if nothing changed
      if (JSON.stringify(renumbered) === JSON.stringify(current)) return prev;

      return { ...prev, proposal: { ...prev.proposal, alternates: renumbered } };
    });
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [
    state.labelsBidPackage,
    state.heightAdder,
    state.jobCondMult,
    state.savedRuns,    state.savedRacks,    state.savedMCHR,  state.savedThreeWay,
    state.savedData,    state.savedFA,       state.savedCans,  state.savedGear,
    state.savedCustomDev, state.savedTM,     state.savedLV,    state.savedCustomAsm,
    state.savedHAR,     state.savedFloorBox, state.asms,       state.savedPanels,
  ]);

  // ── Bullet library state ────────────────────────────────────────

  const [savedBullets, setSavedBullets] = useState<string[]>(() => {
    try {
      return JSON.parse(localStorage.getItem('ore_scope_bullets') ?? '[]');
    } catch { return []; }
  });

  const [showBulletPicker, setShowBulletPicker] =
    useState<{ sectionIdx: number } | null>(null);

  const [bulletPickerTab, setBulletPickerTab] =
    useState<'saved' | 'library'>('library');

  const [bulletSearch, setBulletSearch] = useState('');

  function saveBulletLibrary(bullets: string[]) {
    setSavedBullets(bullets);
    localStorage.setItem('ore_scope_bullets', JSON.stringify(bullets));
  }

  function toggleSavedBullet(text: string) {
    const trimmed = text.trim();
    if (!trimmed) return;
    if (savedBullets.includes(trimmed)) {
      saveBulletLibrary(savedBullets.filter(b => b !== trimmed));
    } else {
      saveBulletLibrary([...savedBullets, trimmed]);
    }
  }

  function removeSavedBullet(idx: number) {
    saveBulletLibrary(savedBullets.filter((_, i) => i !== idx));
  }

  function insertBullet(sectionIdx: number, bullet: string) {
    patch('scopeSections', p.scopeSections.map((s, i) =>
      i === sectionIdx ? { ...s, items: [...s.items, bullet] } : s,
    ));
    setShowBulletPicker(null);
  }

  // ── Scope sections ──────────────────────────────────────────────

  const addSection = () =>
    patch('scopeSections', [
      ...p.scopeSections,
      { id: uid(), title: 'New Section', items: [''] },
    ]);

  const updateSection = (id: string, changes: Partial<ScopeSection>) =>
    patch('scopeSections', p.scopeSections.map(s =>
      s.id === id ? { ...s, ...changes } : s,
    ));

  const removeSection = (id: string) =>
    patch('scopeSections', p.scopeSections.filter(s => s.id !== id));

  const moveSection = (id: string, dir: -1 | 1) => {
    const arr = [...p.scopeSections];
    const i = arr.findIndex(s => s.id === id);
    const j = i + dir;
    if (i < 0 || j < 0 || j >= arr.length) return;
    [arr[i], arr[j]] = [arr[j], arr[i]];
    patch('scopeSections', arr);
  };

  const updateBullet = (sectionId: string, idx: number, value: string) => {
    const sec = p.scopeSections.find(s => s.id === sectionId);
    if (!sec) return;
    const items = [...sec.items];
    items[idx] = value;
    updateSection(sectionId, { items });
  };

  const removeBullet = (sectionId: string, idx: number) => {
    const sec = p.scopeSections.find(s => s.id === sectionId);
    if (!sec) return;
    updateSection(sectionId, { items: sec.items.filter((_, i) => i !== idx) });
  };

  // ── Alternates ──────────────────────────────────────────────────

  const addAlternate = () => {
    const nextNum = (p.alternates[p.alternates.length - 1]?.number ?? 0) + 1;
    patch('alternates', [
      ...p.alternates,
      { id: uid(), number: nextNum, title: `Alternate ${nextNum}`, desc: '', price: 0 },
    ]);
  };

  const updateAlternate = (id: string, changes: Partial<AddAlternate>) =>
    patch('alternates', p.alternates.map(a =>
      a.id === id ? { ...a, ...changes } : a,
    ));

  const removeAlternate = (id: string) =>
    patch('alternates', p.alternates.filter(a => a.id !== id));

  // ── Inclusions / Exclusions ─────────────────────────────────────

  const addListItem = (key: 'inclusions' | 'exclusions') =>
    patch(key, [...p[key], '']);

  const updateListItem = (key: 'inclusions' | 'exclusions', idx: number, val: string) => {
    const arr = [...p[key]];
    arr[idx] = val;
    patch(key, arr);
  };

  const removeListItem = (key: 'inclusions' | 'exclusions', idx: number) =>
    patch(key, p[key].filter((_, i) => i !== idx));

  // ── Print / Download PDF ────────────────────────────────────────

  const [downloading, setDownloading] = useState(false);

  const handlePrint = () => {
    const win = window.open('', '_blank');
    if (!win) return;
    win.document.write(buildPrintHtml(p, state.jobName, displayBaseBid));
    win.document.close();
    win.focus();
    setTimeout(() => win.print(), 300);
  };

  const handleDownloadPdf = async () => {
    setDownloading(true);
    try {
      const payload: ProposalPdfData = {
        jobName:        state.jobName   || 'Estimate',
        jobNumber:      state.jobNumber || '',
        clientCompany:  p.clientCompany || '',
        clientAttn:     p.clientAttn    || '',
        proposalDate:   p.proposalDate,
        validDays:      p.validDays,
        workingHours:   p.workingHours,
        scopeIntro:     p.scopeIntro,
        scopeSections:  p.scopeSections,
        alternates:     p.alternates,
        inclusions:     p.inclusions,
        exclusions:     p.exclusions,
        warrantyText:   p.warrantyText,
        paymentTerms:   p.paymentTerms,
        paymentNote:    p.paymentNote,
        validityNote:   p.validityNote,
        depositEnabled: p.depositEnabled,
        depositPercent: p.depositPercent,
        grandTotal:     correctGrandTotal,
      };

      const res = await fetch('/api/pdf/proposal', {
        method:  'POST',
        headers: { 'Content-Type': 'application/json' },
        body:    JSON.stringify(payload),
      });

      if (!res.ok) throw new Error('PDF generation failed');

      const blob    = await res.blob();
      const url     = URL.createObjectURL(blob);
      const a       = document.createElement('a');
      const jobSlug = (state.jobNumber || 'proposal').replace(/[^a-z0-9]/gi, '_');
      a.href        = url;
      a.download    = `Oak_Ridge_Electrical_${jobSlug}_Proposal.pdf`;
      a.click();
      URL.revokeObjectURL(url);
    } catch (err) {
      console.error('PDF download error:', err);
      alert('Failed to generate PDF. Please try again.');
    } finally {
      setDownloading(false);
    }
  };

  // ── Preview: valid-until date ───────────────────────────────────
  const validUntil = useMemo(() => {
    const d = new Date(p.proposalDate + 'T12:00:00');
    d.setDate(d.getDate() + p.validDays);
    return d.toLocaleDateString('en-US', { month: 'long', day: 'numeric', year: 'numeric' });
  }, [p.proposalDate, p.validDays]);

  const fmtDate = (iso: string) =>
    new Date(iso + 'T12:00:00').toLocaleDateString('en-US', {
      month: 'long', day: 'numeric', year: 'numeric',
    });

  // ─────────────────────────────────────
  // Render
  // ─────────────────────────────────────

  return (
    <div className="flex gap-4 max-w-[1400px] h-[calc(100vh-148px)]">

      {/* ── Left: Editor ──────────────────────────────────────────── */}
      <div className="w-80 shrink-0 overflow-y-auto flex flex-col gap-3 pb-4 pr-1">

        {/* Client Info */}
        <Card title="Client Info">
          <LabelInput
            label="Company / GC"
            value={p.clientCompany}
            onChange={v => patch('clientCompany', v)}
            placeholder="GC Company Name"
          />
          {state.jobInfo.gcCompany && (
            <button
              onClick={() => setState(s => ({
                ...s,
                proposal: {
                  ...s.proposal,
                  clientCompany: s.jobInfo.gcCompany,
                  clientAttn:    s.jobInfo.gcContactName || '',
                },
              }))}
              className="text-xs text-blue-500 hover:text-blue-700 mt-1 mb-1">
              ↩ Pull from GC info
            </button>
          )}
          <LabelInput
            label="Attn / Contact"
            value={p.clientAttn}
            onChange={v => patch('clientAttn', v)}
            placeholder="Contact Name"
          />
        </Card>

        {/* Proposal Details */}
        <Card title="Proposal Details">
          <LabelInput
            label="Date"
            value={p.proposalDate}
            onChange={v => patch('proposalDate', v)}
            type="date"
          />
          <LabelInput
            label="Valid For (days)"
            value={p.validDays}
            onChange={v => patch('validDays', parseInt(v) || 30)}
            type="number"
          />
          <LabelInput
            label="Working Hours"
            value={p.workingHours}
            onChange={v => patch('workingHours', v)}
          />
        </Card>

        {/* Scope Intro */}
        <Card title="Scope Introduction">
          <textarea
            className="w-full border border-gray-200 rounded px-2 py-1.5 text-sm focus:outline-none focus:border-[#1e3a8a] resize-none"
            rows={4}
            defaultValue={p.scopeIntro}
            onBlur={e => patch('scopeIntro', e.target.value)}
            key={p.scopeIntro}
          />
        </Card>

        {/* Scope Sections */}
        <Card title="Scope Sections">
          {(hasFAWork && !hasFASection) && (
            <div className="flex items-center gap-3 bg-amber-50 border border-amber-200 rounded-lg px-4 py-3 mb-3">
              <span className="text-amber-500 text-lg">🔔</span>
              <div className="flex-1">
                <div className="text-sm font-semibold text-amber-800">Your estimate includes Fire Alarm work</div>
                <div className="text-xs text-amber-600">No Fire Alarm scope section found in proposal</div>
              </div>
              <button
                onClick={() => {
                  const bullets = PRELOADED_SCOPE_BULLETS['Fire Alarm'] ?? [];
                  patch('scopeSections', [
                    ...p.scopeSections,
                    { id: uid(), title: 'Fire Alarm', items: bullets },
                  ]);
                }}
                className="px-3 py-1.5 text-xs font-semibold rounded bg-amber-500 text-white hover:bg-amber-600 whitespace-nowrap">
                + Add FA Section
              </button>
            </div>
          )}
          {((hasDataWork || hasLVWork) && !hasDataSection) && (
            <div className="flex items-center gap-3 bg-blue-50 border border-blue-200 rounded-lg px-4 py-3 mb-3">
              <span className="text-blue-500 text-lg">🔔</span>
              <div className="flex-1">
                <div className="text-sm font-semibold text-blue-800">Your estimate includes Data / LV work</div>
                <div className="text-xs text-blue-600">No Data / Low Voltage scope section found</div>
              </div>
              <button
                onClick={() => {
                  const bullets = PRELOADED_SCOPE_BULLETS['Data / Low Voltage'] ?? [];
                  patch('scopeSections', [
                    ...p.scopeSections,
                    { id: uid(), title: 'Data / Low Voltage', items: bullets },
                  ]);
                }}
                className="px-3 py-1.5 text-xs font-semibold rounded bg-blue-600 text-white hover:bg-blue-700 whitespace-nowrap">
                + Add Data/LV Section
              </button>
            </div>
          )}
          {p.scopeSections.map((sec, si) => (
            <div key={sec.id} className="mb-3 border border-gray-100 rounded p-2 bg-gray-50">
              {/* Section header */}
              <div className="flex items-center gap-1 mb-1.5">
                <span className="text-xs text-gray-500 font-medium w-4">{si + 1}.</span>
                <input
                  className="flex-1 border border-gray-200 rounded px-1.5 py-0.5 text-xs font-medium focus:outline-none focus:border-[#1e3a8a]"
                  defaultValue={sec.title}
                  onBlur={e => updateSection(sec.id, { title: e.target.value })}
                  key={sec.title}
                />
                <button
                  onClick={() => moveSection(sec.id, -1)}
                  disabled={si === 0}
                  className="text-gray-400 hover:text-gray-600 disabled:opacity-30 text-xs px-0.5"
                  title="Move up"
                >↑</button>
                <button
                  onClick={() => moveSection(sec.id, 1)}
                  disabled={si === p.scopeSections.length - 1}
                  className="text-gray-400 hover:text-gray-600 disabled:opacity-30 text-xs px-0.5"
                  title="Move down"
                >↓</button>
                <button
                  onClick={() => removeSection(sec.id)}
                  className="text-red-400 hover:text-red-600 text-xs px-0.5"
                  title="Remove section"
                >✕</button>
              </div>
              {/* Bullets */}
              {sec.items.map((item, ii) => (
                <div key={ii} className="flex items-center gap-1 mb-1">
                  <span className="text-gray-300 text-xs">•</span>
                  <input
                    className="flex-1 border border-gray-100 rounded px-1.5 py-0.5 text-xs focus:outline-none focus:border-[#1e3a8a] bg-white"
                    defaultValue={item}
                    onBlur={e => updateBullet(sec.id, ii, e.target.value)}
                    key={`${sec.id}-${ii}-${item}`}
                    placeholder="Bullet point…"
                  />
                  <button
                    type="button"
                    onClick={() => toggleSavedBullet(item)}
                    title={savedBullets.includes(item.trim()) ? 'Remove from saved' : 'Save to library'}
                    className={`flex-shrink-0 text-sm px-1 transition-colors ${
                      savedBullets.includes(item.trim())
                        ? 'text-yellow-400'
                        : 'text-gray-200 hover:text-yellow-300'
                    }`}
                  >⭐</button>
                  <button
                    onClick={() => removeBullet(sec.id, ii)}
                    className="text-red-300 hover:text-red-500 text-xs"
                  >✕</button>
                </div>
              ))}
              <div className="flex gap-3 mt-1 pl-1">
                <button
                  type="button"
                  onClick={() => updateSection(sec.id, { items: [...sec.items, ''] })}
                  className="text-xs text-blue-500 hover:text-blue-600 flex items-center gap-1"
                >+ New bullet</button>
                <button
                  type="button"
                  onClick={() => {
                    setShowBulletPicker({ sectionIdx: si });
                    setBulletPickerTab('library');
                    setBulletSearch('');
                  }}
                  className="text-xs text-yellow-600 hover:text-yellow-700 flex items-center gap-1"
                >⭐ From library</button>
              </div>
            </div>
          ))}
          <button
            onClick={addSection}
            className="w-full text-xs border border-dashed border-[#1e3a8a] text-[#1e3a8a] rounded py-1 hover:bg-blue-50 transition-colors"
          >+ Add Section</button>
        </Card>

        {/* Base Bid pricing override */}
        <Card title="Pricing">
          <div className="mb-1">
            <label className="text-xs font-semibold text-[#1e3a8a] uppercase tracking-wide block mb-1">
              Base Bid Total
            </label>
            <div className="flex items-center gap-2">
              <span className="text-gray-500 text-sm">$</span>
              <input
                type="number"
                value={(baseBidOverride ?? baseBidTotal).toFixed(2)}
                onChange={e =>
                  setBaseBidOverride(
                    e.target.value === '' ? null : parseFloat(e.target.value),
                  )
                }
                className="flex-1 border border-gray-300 rounded px-2 py-1 text-sm font-mono text-gray-800 focus:outline-none focus:border-[#1e3a8a]"
              />
              {baseBidOverride !== null && (
                <button
                  onClick={() => setBaseBidOverride(null)}
                  className="text-xs text-blue-500 hover:text-blue-700 whitespace-nowrap"
                  title="Reset to calculated value"
                >
                  ↺ Reset
                </button>
              )}
            </div>
            <p className="text-xs text-gray-400 mt-1">
              Auto: {fmt$(baseBidTotal)} — edit to override
            </p>
          </div>
        </Card>

        {/* Alternates */}
        <Card title="Add Alternates">
          {p.alternates.map((alt) => (
            <div
              key={alt.id}
              className={`mb-2 border rounded p-2 ${
                alt.bidPackage
                  ? 'border-blue-200 bg-blue-50/40'
                  : 'border-gray-100 bg-gray-50'
              }`}
            >
              <div className="flex items-center gap-1 mb-1.5">
                <span className="text-xs font-semibold text-gray-600">Alt {alt.number}</span>
                {alt.bidPackage && (
                  <span
                    className="text-[10px] font-semibold px-1.5 py-0.5 rounded bg-blue-100 text-blue-600 whitespace-nowrap"
                    title="Price auto-synced from Estimator label system"
                  >
                    ⟳ Estimator
                  </span>
                )}
                <input
                  className="flex-1 border border-gray-200 rounded px-1.5 py-0.5 text-xs font-medium focus:outline-none focus:border-[#1e3a8a]"
                  defaultValue={alt.title}
                  onBlur={e => updateAlternate(alt.id, { title: e.target.value })}
                  key={alt.title}
                  placeholder="Title"
                />
                <button
                  onClick={() => removeAlternate(alt.id)}
                  className="text-red-400 hover:text-red-600 text-xs"
                >✕</button>
              </div>
              <input
                className="w-full border border-gray-100 rounded px-1.5 py-0.5 text-xs mb-1 focus:outline-none focus:border-[#1e3a8a] bg-white"
                defaultValue={alt.desc}
                onBlur={e => updateAlternate(alt.id, { desc: e.target.value })}
                key={alt.desc}
                placeholder="Description"
              />
              <div className="flex items-center gap-1">
                <span className="text-xs text-gray-500">$</span>
                {alt.bidPackage ? (
                  /* Estimator-driven: price is read-only, styled navy/orange */
                  <div
                    className="flex-1 border border-blue-200 rounded px-1.5 py-0.5 text-xs bg-blue-50 text-[#1e3a8a] font-semibold font-mono select-all cursor-default"
                    title="Auto-calculated from Estimator label system — edit assemblies in the Estimator to change this price"
                  >
                    {fmt$(alt.price)}
                  </div>
                ) : (
                  <input
                    type="number"
                    className="flex-1 border border-gray-100 rounded px-1.5 py-0.5 text-xs focus:outline-none focus:border-[#1e3a8a] bg-white"
                    defaultValue={alt.price}
                    onBlur={e => updateAlternate(alt.id, { price: parseFloat(e.target.value) || 0 })}
                    key={alt.price}
                    placeholder="0.00"
                  />
                )}
              </div>
            </div>
          ))}
          <button
            onClick={addAlternate}
            className="w-full text-xs border border-dashed border-[#1e3a8a] text-[#1e3a8a] rounded py-1 hover:bg-blue-50 transition-colors"
          >+ Add Alternate</button>
        </Card>

        {/* Inclusions */}
        <Card title="Inclusions">
          {p.inclusions.map((item, i) => (
            <div key={i} className="flex items-center gap-1 mb-1">
              <span className="text-gray-300 text-xs">•</span>
              <input
                className="flex-1 border border-gray-100 rounded px-1.5 py-0.5 text-xs focus:outline-none focus:border-[#1e3a8a]"
                defaultValue={item}
                onBlur={e => updateListItem('inclusions', i, e.target.value)}
                key={`inc-${i}-${item}`}
              />
              <button
                onClick={() => removeListItem('inclusions', i)}
                className="text-red-300 hover:text-red-500 text-xs"
              >✕</button>
            </div>
          ))}
          <div className="flex gap-2 mt-1">
            <button
              onClick={() => addListItem('inclusions')}
              className="text-xs text-[#1e3a8a] hover:underline"
            >+ Add</button>
            <button
              onClick={() => patch('inclusions', [...DEFAULT_INCLUSIONS])}
              className="text-xs text-gray-400 hover:underline"
            >Reset</button>
          </div>
        </Card>

        {/* Exclusions */}
        <Card title="Exclusions">
          {p.exclusions.map((item, i) => (
            <div key={i} className="flex items-center gap-1 mb-1">
              <span className="text-gray-300 text-xs">•</span>
              <input
                className="flex-1 border border-gray-100 rounded px-1.5 py-0.5 text-xs focus:outline-none focus:border-[#1e3a8a]"
                defaultValue={item}
                onBlur={e => updateListItem('exclusions', i, e.target.value)}
                key={`exc-${i}-${item}`}
              />
              <button
                onClick={() => removeListItem('exclusions', i)}
                className="text-red-300 hover:text-red-500 text-xs"
              >✕</button>
            </div>
          ))}
          <div className="flex gap-2 mt-1">
            <button
              onClick={() => addListItem('exclusions')}
              className="text-xs text-[#1e3a8a] hover:underline"
            >+ Add</button>
            <button
              onClick={() => patch('exclusions', [...DEFAULT_EXCLUSIONS])}
              className="text-xs text-gray-400 hover:underline"
            >Reset</button>
          </div>
        </Card>

        {/* Warranty */}
        <Card title="Warranty">
          <textarea
            className="w-full border border-gray-200 rounded px-2 py-1.5 text-sm focus:outline-none focus:border-[#1e3a8a] resize-none"
            rows={3}
            defaultValue={p.warrantyText}
            onBlur={e => patch('warrantyText', e.target.value)}
            key={p.warrantyText}
          />
          <button
            onClick={() => patch('warrantyText', DEFAULT_WARRANTY)}
            className="text-xs text-gray-400 hover:underline mt-1"
          >Reset to default</button>
        </Card>

        {/* Deposit Request */}
        <Card title="Deposit Request">
          <label className="flex items-center gap-2 cursor-pointer mb-2">
            <input
              type="checkbox"
              checked={p.depositEnabled}
              onChange={e => patch('depositEnabled', e.target.checked)}
              className="rounded accent-[#1e3a8a]"
            />
            <span className="text-sm">Include deposit request</span>
          </label>
          {p.depositEnabled && (
            <div className="flex items-center gap-2">
              <span className="text-xs text-gray-500">Deposit %</span>
              <input
                type="number"
                min={1}
                max={100}
                className="w-20 border border-gray-200 rounded px-2 py-1 text-sm focus:outline-none focus:border-[#1e3a8a]"
                defaultValue={p.depositPercent}
                onBlur={e => patch('depositPercent', Math.min(100, Math.max(1, parseInt(e.target.value) || 30)))}
                key={p.depositPercent}
              />
              <span className="text-xs text-gray-500">
                = {fmt$(displayBaseBid * p.depositPercent / 100)}
              </span>
            </div>
          )}
        </Card>

        {/* Payment Terms */}
        <Card title="Payment Terms">
          <div className="flex flex-col gap-1 mb-2">
            {(Object.entries(PAYMENT_TERM_LABELS) as [PaymentTerms, string][]).map(([key, label]) => (
              <label key={key} className="flex items-center gap-2 cursor-pointer">
                <input
                  type="radio"
                  name="paymentTerms"
                  value={key}
                  checked={p.paymentTerms === key}
                  onChange={() => patch('paymentTerms', key)}
                  className="accent-[#1e3a8a]"
                />
                <span className="text-sm">{label}</span>
              </label>
            ))}
          </div>
          <LabelInput
            label="Payment Note (optional)"
            value={p.paymentNote}
            onChange={v => patch('paymentNote', v)}
            placeholder="e.g. Customer-furnished scissor lift required"
          />
          <LabelInput
            label="Validity Note"
            value={p.validityNote}
            onChange={v => patch('validityNote', v)}
          />
        </Card>

        {/* Download PDF + Print */}
        <div className="flex gap-2">
          <button
            onClick={handleDownloadPdf}
            disabled={downloading}
            className="flex-1 flex items-center justify-center gap-2 py-2.5 rounded-lg bg-[#1e3a8a] text-white font-semibold text-sm hover:bg-[#1e3a8a] transition-colors disabled:opacity-50 disabled:cursor-not-allowed">
            {downloading ? '⏳ Generating...' : '⬇ Download PDF'}
          </button>
          <button
            onClick={handlePrint}
            className="flex items-center gap-1.5 px-3 py-2.5 rounded-lg border border-gray-200 text-gray-500 text-xs hover:bg-gray-50 transition-colors">
            🖨 Print
          </button>
        </div>

      </div>

      {/* ── Right: Live Preview ────────────────────────────────────── */}
      <div className="flex-1 overflow-y-auto">
        <div
          className="bg-white border border-gray-300 rounded-lg shadow-sm mx-auto p-8 text-xs leading-relaxed"
          style={{ maxWidth: 760, fontFamily: 'Arial, sans-serif', color: '#1a1a1a' }}
        >

          {/* Header */}
          <div style={{
            display: 'flex',
            justifyContent: 'space-between',
            alignItems: 'flex-start',
            marginBottom: '16px',
          }}>
            <div>
              <img
                src="/logo.png"
                alt="Oak Ridge Electrical LLC"
                style={{ height: '80px', width: 'auto', objectFit: 'contain' }}
              />
              <div style={{ fontSize: '9pt', color: '#555', lineHeight: 1.5, marginTop: 4 }}>
                {CO_ADDR}<br />
                {CO_PHONE} · {CO_EMAIL}<br />
                {CO_LICENSE}
              </div>
            </div>
            <div style={{ textAlign: 'right' }}>
              <div style={{
                fontSize: '24pt', fontWeight: 'bold', color: '#1e3a8a',
                letterSpacing: '0.02em',
              }}>
                ELECTRICAL PROPOSAL
              </div>
              <div style={{
                fontSize: '13pt', fontWeight: 'bold', color: '#c8601a',
                marginTop: '4px',
              }}>
                {state.jobName || '[Project Name]'}
              </div>
              <div style={{ fontSize: '10pt', color: '#666', marginTop: '4px' }}>
                Job #: {state.jobNumber || '—'} | Date:{' '}
                {p.proposalDate
                  ? new Date(p.proposalDate + 'T12:00:00')
                      .toLocaleDateString('en-US', {
                        year: 'numeric', month: 'long', day: 'numeric',
                      })
                  : '—'}
              </div>
            </div>
          </div>
          <hr style={{ borderTop: '2px solid #1e3a8a', margin: '0 0 16px 0' }} />

          {/* Proposal To */}
          <div className="flex gap-8 mb-4">
            <div>
              <div className="font-semibold text-gray-700 mb-0.5">Proposal To:</div>
              <div>{p.clientCompany || <span className="text-gray-300 italic">Company name</span>}</div>
              {p.clientAttn && <div>Attn: {p.clientAttn}</div>}
            </div>
            <div>
              <div className="font-semibold text-gray-700 mb-0.5">Re:</div>
              <div>{state.jobName}</div>
              <div className="mt-0.5"><span className="font-semibold text-gray-700">Working Hours:</span> {p.workingHours}</div>
            </div>
          </div>

          {/* Scope intro */}
          <p className="mb-3 leading-relaxed">{p.scopeIntro}</p>

          {/* Scope Sections */}
          {p.scopeSections.length > 0 && (
            <>
              <SectionHeading>Scope of Work</SectionHeading>
              {p.scopeSections.map((sec, si) => (
                <div key={sec.id} className="mb-2">
                  <div className="font-semibold">{si + 1}. {sec.title}</div>
                  <ul className="list-disc pl-5 mt-0.5">
                    {sec.items.filter(Boolean).map((item, ii) => (
                      <li key={ii}>{item}</li>
                    ))}
                  </ul>
                </div>
              ))}
            </>
          )}

          {/* Pricing */}
          <SectionHeading>Pricing</SectionHeading>
          <table className="w-full border-collapse mb-2 text-xs">
            <tbody>
              <tr className="font-semibold" style={{ background: '#f0f4fa' }}>
                <td className="px-2.5 py-2 border border-gray-200">Base Bid — Complete Electrical Scope</td>
                <td className="px-2.5 py-2 border border-gray-200 text-right font-bold text-sm">{fmt$(displayBaseBid)}</td>
              </tr>
            </tbody>
          </table>

          {p.alternates.length > 0 && (
            <>
              <div className="text-xs font-semibold text-gray-600 mt-2 mb-1">Add Alternates</div>
              <table className="w-full border-collapse text-xs">
                <thead>
                  <tr style={{ background: '#f0f4fa' }}>
                    <th className="px-2 py-1.5 border border-gray-200 text-left font-semibold">Alt #</th>
                    <th className="px-2 py-1.5 border border-gray-200 text-left font-semibold">Title</th>
                    <th className="px-2 py-1.5 border border-gray-200 text-left font-semibold">Description</th>
                    <th className="px-2 py-1.5 border border-gray-200 text-right font-semibold">Price</th>
                  </tr>
                </thead>
                <tbody>
                  {p.alternates.map(alt => (
                    <tr key={alt.id}>
                      <td className="px-2 py-1.5 border border-gray-200">Add Alt {alt.number}</td>
                      <td className="px-2 py-1.5 border border-gray-200">{alt.title}</td>
                      <td className="px-2 py-1.5 border border-gray-200">{alt.desc}</td>
                      <td className="px-2 py-1.5 border border-gray-200 text-right">{fmt$(alt.price)}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </>
          )}

          {/* Inclusions / Exclusions */}
          <div className="flex gap-6 mt-3">
            <div className="flex-1">
              <SectionHeading>Inclusions</SectionHeading>
              <ul className="list-disc pl-4">
                {p.inclusions.filter(Boolean).map((item, i) => <li key={i}>{item}</li>)}
              </ul>
            </div>
            <div className="flex-1">
              <SectionHeading>Exclusions</SectionHeading>
              <ul className="list-disc pl-4">
                {p.exclusions.filter(Boolean).map((item, i) => <li key={i}>{item}</li>)}
              </ul>
            </div>
          </div>

          {/* Warranty */}
          <SectionHeading>Warranty</SectionHeading>
          <p>{p.warrantyText}</p>

          {/* Deposit */}
          {p.depositEnabled && (
            <div style={{
              background: '#e8f0fe',
              border: '1px solid #4a7bc8',
              borderRadius: 6,
              padding: '10px 14px',
              marginTop: 12,
              marginBottom: 4,
            }}>
              <div className="font-semibold text-sm" style={{ color: '#1e3a8a' }}>
                Deposit Request
              </div>
              <div className="mt-1">
                A deposit of{' '}
                <strong>{p.depositPercent}% ({fmt$(displayBaseBid * p.depositPercent / 100)})</strong>{' '}
                is required to schedule and begin work.
              </div>
            </div>
          )}

          {/* Payment Terms */}
          <SectionHeading>Payment Terms</SectionHeading>
          <p className="whitespace-pre-line">{getPaymentParagraph(p.paymentTerms)}</p>
          {p.paymentNote && <p className="italic mt-1">{p.paymentNote}</p>}

          {/* Validity */}
          <p className="italic mt-2">{p.validityNote}</p>

          {/* Acceptance */}
          <SectionHeading>Acceptance</SectionHeading>
          <p>
            The above prices, specifications, and conditions are satisfactory and are hereby accepted.
            You are authorized to do the work as specified. Payment will be made as outlined above.
          </p>
          <div className="flex gap-10 mt-6">
            <div className="flex-1">
              <div className="border-b border-gray-500 h-8" />
              <div className="mt-1 text-gray-600">Authorized Signature — Owner / GC</div>
              <div className="text-gray-500 mt-0.5">Date: _______________</div>
            </div>
            <div className="flex-1">
              <div className="border-b border-gray-500 h-8" />
              <div className="mt-1 text-gray-600">{CO_NAME}</div>
              <div className="text-gray-500 mt-0.5">Date: _______________</div>
            </div>
          </div>

          {/* Footer */}
          <div className="mt-8 pt-2 border-t border-gray-200 text-center text-gray-400" style={{ fontSize: 10 }}>
            {CO_NAME} · {CO_PHONE} · {CO_EMAIL} · {CO_LICENSE}
          </div>

        </div>
      </div>

      {/* ── Bullet Picker Modal ──────────────────────────────────────── */}
      {showBulletPicker !== null && (
        <div
          className="fixed inset-0 bg-black/50 z-50 flex items-center justify-center p-4"
          onClick={() => setShowBulletPicker(null)}
        >
          <div
            className="bg-white rounded-xl shadow-2xl w-full max-w-2xl flex flex-col"
            style={{ maxHeight: '80vh' }}
            onClick={e => e.stopPropagation()}
          >
            {/* Modal header */}
            <div className="flex items-center justify-between px-5 py-4 border-b border-gray-200">
              <h3 className="font-bold text-[#1e3a8a] text-lg">Scope Bullet Library</h3>
              <button
                onClick={() => setShowBulletPicker(null)}
                className="text-gray-400 hover:text-gray-600 text-xl"
              >✕</button>
            </div>

            {/* Tabs */}
            <div className="flex border-b border-gray-200 px-5">
              {(['library', 'saved'] as const).map(tab => (
                <button
                  key={tab}
                  onClick={() => setBulletPickerTab(tab)}
                  className={`px-4 py-2 text-sm font-semibold border-b-2 transition-colors capitalize ${
                    bulletPickerTab === tab
                      ? 'border-[#1e3a8a] text-[#1e3a8a]'
                      : 'border-transparent text-gray-400 hover:text-gray-600'
                  }`}
                >
                  {tab === 'library'
                    ? '📚 Full Library'
                    : `⭐ Saved (${savedBullets.length})`}
                </button>
              ))}
            </div>

            {/* Search */}
            <div className="px-5 py-3 border-b border-gray-100">
              <input
                type="text"
                placeholder="Search bullets..."
                value={bulletSearch}
                onChange={e => setBulletSearch(e.target.value)}
                className="w-full border border-gray-300 rounded-lg px-3 py-2 text-sm focus:outline-none focus:border-blue-400"
              />
            </div>

            {/* Content */}
            <div className="flex-1 overflow-y-auto px-5 py-3">

              {bulletPickerTab === 'library' && (
                <div className="space-y-4">
                  {Object.entries(PRELOADED_SCOPE_BULLETS).map(([category, bullets]) => {
                    const filtered = bullets.filter(b =>
                      !bulletSearch || b.toLowerCase().includes(bulletSearch.toLowerCase())
                    );
                    if (!filtered.length) return null;
                    return (
                      <div key={category}>
                        <div className="text-xs font-bold tracking-widest uppercase text-[#1e3a8a] mb-2">
                          {category}
                        </div>
                        <div className="space-y-1">
                          {filtered.map((bullet, bi) => (
                            <div key={bi} className="flex items-start gap-2 p-2 rounded hover:bg-blue-50 group">
                              <button
                                onClick={() => insertBullet(showBulletPicker!.sectionIdx, bullet)}
                                className="flex-1 text-left text-sm text-gray-700 leading-snug"
                              >
                                {bullet}
                              </button>
                              <button
                                onClick={e => { e.stopPropagation(); toggleSavedBullet(bullet); }}
                                title={savedBullets.includes(bullet.trim()) ? 'Remove from saved' : 'Save for quick access'}
                                className={`flex-shrink-0 text-sm transition-colors mt-0.5 ${
                                  savedBullets.includes(bullet.trim())
                                    ? 'text-yellow-400'
                                    : 'text-gray-200 group-hover:text-yellow-300'
                                }`}
                              >⭐</button>
                            </div>
                          ))}
                        </div>
                      </div>
                    );
                  })}
                </div>
              )}

              {bulletPickerTab === 'saved' && (
                <div>
                  {savedBullets.length === 0 ? (
                    <div className="text-center py-10 text-gray-400">
                      <div className="text-3xl mb-2">⭐</div>
                      <div className="text-sm">No saved bullets yet.</div>
                      <div className="text-xs mt-1">
                        Star bullets in the Full Library tab or directly on scope bullets to save them here.
                      </div>
                    </div>
                  ) : (
                    <div className="space-y-1">
                      {savedBullets
                        .filter(b => !bulletSearch || b.toLowerCase().includes(bulletSearch.toLowerCase()))
                        .map((bullet, bi) => (
                          <div key={bi} className="flex items-start gap-2 p-2 rounded hover:bg-blue-50 group">
                            <button
                              onClick={() => insertBullet(showBulletPicker!.sectionIdx, bullet)}
                              className="flex-1 text-left text-sm text-gray-700 leading-snug"
                            >
                              {bullet}
                            </button>
                            <button
                              onClick={e => { e.stopPropagation(); removeSavedBullet(savedBullets.indexOf(bullet)); }}
                              className="flex-shrink-0 text-xs text-gray-300 hover:text-red-400 opacity-0 group-hover:opacity-100 transition-opacity mt-0.5"
                            >✕</button>
                          </div>
                        ))}
                    </div>
                  )}
                </div>
              )}

            </div>

            {/* Footer */}
            <div className="px-5 py-3 border-t border-gray-100 text-xs text-gray-400">
              Click any bullet to insert it into the scope section. ⭐ saves it to your personal library for quick access.
            </div>
          </div>
        </div>
      )}

    </div>
  );
}

// ── Small presentational helper ───────────────────────────────────────────────

function SectionHeading({ children }: { children: React.ReactNode }) {
  return (
    <div
      className="font-semibold text-xs uppercase tracking-wide mt-3 mb-1 pb-0.5 border-b"
      style={{ color: '#1e3a8a', borderColor: '#1e3a8a', letterSpacing: '.05em' }}
    >
      {children}
    </div>
  );
}
